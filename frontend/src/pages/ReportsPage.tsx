import React from 'react';
import { apiClient } from '../services/apiClient';
import type { WorkflowStatus } from '../types/api';

interface ReportsPageProps {
  workflow: WorkflowStatus | null;
}

export const ReportsPage: React.FC<ReportsPageProps> = ({ workflow }) => {
  const [isDownloading, setIsDownloading] = React.useState<boolean>(false);
  const [downloadError, setDownloadError] = React.useState<string | null>(null);

  const handleDownloadOriginal = async () => {
    if (!workflow) return;
    setIsDownloading(true);
    setDownloadError(null);
    try {
      const blob = await apiClient.downloadDocument(workflow.document_id);
      const url = window.URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = `document_${workflow.document_id}.pdf`;
      document.body.appendChild(a);
      a.click();
      window.URL.revokeObjectURL(url);
      document.body.removeChild(a);
    } catch (err) {
      setDownloadError((err as Error).message || 'Failed to download document artifact');
    } finally {
      setIsDownloading(false);
    }
  };

  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: 'var(--space-lg)' }}>
      <div className="card">
        <div className="card-header">
          <div>
            <h3>Financial Document Evidence Report</h3>
            <div style={{ fontSize: '0.75rem', color: 'var(--color-text-secondary)' }}>
              Deterministic audit bundle generated by ReportLab engine and committed to object storage
            </div>
          </div>
        </div>

        <div className="card-body">
          <div className="info-notice section-gap">
            <span className="notice-icon">📑</span>
            <div>
              <strong>Audit-Sealed Evidence Summary:</strong> PaperTrail compiles extraction results, deterministic forensic rule evaluations, compliance certificates, and cryptographic hashes into an immutable evidence package.
            </div>
          </div>

          <div className="detail-grid section-gap">
            <div className="detail-item">
              <span className="detail-label">Active Workflow</span>
              <span className="detail-value mono">{workflow?.workflow_id || 'None'}</span>
            </div>
            <div className="detail-item">
              <span className="detail-label">Document Reference</span>
              <span className="detail-value mono">{workflow?.document_id || 'None'}</span>
            </div>
            <div className="detail-item">
              <span className="detail-label">Pipeline State</span>
              <span className="detail-value">{workflow?.current_state || 'None'}</span>
            </div>
            <div className="detail-item">
              <span className="detail-label">Evidence Seal</span>
              <span className="detail-value">
                {['REPORT_GENERATED', 'COMPLETED', 'REQUIRES_REVIEW'].includes(workflow?.current_state || '')
                  ? '✓ Generated & Sealed'
                  : 'Pending Pipeline Execution'}
              </span>
            </div>
          </div>

          {downloadError && (
            <div
              style={{
                marginBottom: 'var(--space-md)',
                padding: 'var(--space-sm)',
                background: 'var(--color-error-bg)',
                border: '1px solid #fecaca',
                borderRadius: 'var(--radius-sm)',
                color: 'var(--color-error)',
                fontSize: '0.8rem',
              }}
            >
              {downloadError}
            </div>
          )}

          <div style={{ display: 'flex', gap: '12px' }}>
            <button
              className="btn btn-primary"
              onClick={handleDownloadOriginal}
              disabled={!workflow || isDownloading}
            >
              {isDownloading ? (
                <>
                  <span className="loading-spinner" /> Downloading Original Document...
                </>
              ) : (
                '⬇ Download Original Document'
              )}
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
